#!/usr/bin/env python3
"""Small, dependency-free menuconfig frontend for miniOS.

The Kconfig files are the human-readable configuration hierarchy.  This
frontend deliberately supports the subset miniOS uses today: one architecture
and board choice plus boolean driver/features.  Output is compatible with GNU
make and C: .config and src/include/generated/autoconf.h.
"""
from __future__ import annotations

import curses
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CONFIG = ROOT / ".config"
HEADER = ROOT / "src/include/generated/autoconf.h"

OPTIONS = [
    ("Architecture", "ARCH_ARM", "ARM 32-bit (Cortex-A7)"),
    ("Architecture", "ARCH_ARM64", "ARM 64-bit (Cortex-A53)"),
    ("Board", "BOARD_100ASK_T113", "100ASK T113-S3"),
    ("Board", "BOARD_RPI3", "Raspberry Pi 3"),
    ("MMC / SDIO", "MMC", "MMC core"),
    ("MMC / SDIO", "MMC_SUNXI", "Allwinner SMHC controller"),
    ("MMC / SDIO", "SDIO", "SDIO bus"),
    ("Networking", "NET", "Networking support"),
    ("Networking", "WLAN", "Wireless LAN"),
    ("Networking", "WLAN_XRADIO", "XRadio family"),
    ("Networking", "WLAN_XRADIO_XR829", "XR829 SDIO device"),
    ("Networking", "XR829_WSM", "WSM command layer"),
    ("Networking", "WPA2_PSK", "WPA2-PSK host crypto"),
    ("Drivers", "I2C", "I2C support"),
    ("Drivers", "VIDEO", "Video capture"),
    ("Drivers", "VIDEO_OV5640", "OV5640 camera"),
    ("File systems", "VFS", "Virtual file system"),
    ("File systems", "MINIFS", "Embedded miniFS"),
    ("Kernel", "USERSPACE", "Userspace and system calls"),
    ("Kernel", "DEBUG_MMU_DUMP", "MMU page-table diagnostics"),
]

DEPS = {
    "MMC_SUNXI": ("MMC", "BOARD_100ASK_T113"), "SDIO": ("MMC",),
    "NET": ("BOARD_100ASK_T113",), "WLAN": ("NET",),
    "WLAN_XRADIO": ("WLAN", "SDIO"),
    "WLAN_XRADIO_XR829": ("WLAN_XRADIO",), "XR829_WSM": ("WLAN_XRADIO_XR829",),
    "WPA2_PSK": ("XR829_WSM",), "VIDEO": ("I2C",),
    "VIDEO_OV5640": ("VIDEO",), "MINIFS": ("VFS",),
}

def defaults():
    return {key: key not in {"ARCH_ARM64", "BOARD_RPI3", "VIDEO",
                             "VIDEO_OV5640", "DEBUG_MMU_DUMP"}
            for _, key, _ in OPTIONS}

def load(path=CONFIG):
    values = defaults()
    if path.exists():
        for line in path.read_text().splitlines():
            if line.startswith("CONFIG_") and "=" in line:
                key, val = line.split("=", 1)
                values[key[7:]] = val == "y"
    normalize(values)
    return values

def normalize(v):
    if v.get("ARCH_ARM64"):
        v["ARCH_ARM"] = False; v["BOARD_RPI3"] = True; v["BOARD_100ASK_T113"] = False
    else:
        v["ARCH_ARM"] = True; v["ARCH_ARM64"] = False; v["BOARD_100ASK_T113"] = True; v["BOARD_RPI3"] = False
    changed = True
    while changed:
        changed = False
        for key, deps in DEPS.items():
            if v.get(key) and not all(v.get(dep) for dep in deps):
                v[key] = False; changed = True

def save(v):
    normalize(v)
    CONFIG.write_text("# Automatically generated by make menuconfig\n" +
                      "".join(f"CONFIG_{key}={'y' if v.get(key) else 'n'}\n"
                              for _, key, _ in OPTIONS))
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    enabled = [f"#define CONFIG_{key} 1\n" for _, key, _ in OPTIONS if v.get(key)]
    HEADER.write_text("/* Automatically generated; do not edit. */\n"
                      "#ifndef MINIOS_GENERATED_AUTOCONF_H\n"
                      "#define MINIOS_GENERATED_AUTOCONF_H\n" +
                      "".join(enabled) + "#endif\n")

def run(stdscr, v):
    try:
        curses.curs_set(0)
    except curses.error:
        pass
    pos = 0
    while True:
        stdscr.erase(); h, w = stdscr.getmaxyx()
        def put(row, text, attr=0):
            if 0 <= row < h - 1 and w > 1:
                try:
                    stdscr.addnstr(row, 0, text, w - 1, attr)
                except curses.error:
                    pass
        put(0, "miniOS Configuration — arrows: move, space: toggle, s: save, q: quit")
        row = 2; last = None
        for i, (group, key, label) in enumerate(OPTIONS):
            if group != last:
                put(row, f"--- {group} ---", curses.A_BOLD); row += 1; last = group
            deps_ok = all(v.get(d) for d in DEPS.get(key, ()))
            mark = "[*]" if v.get(key) else "[ ]"
            text = f" {mark} {label} ({key})" + (" [dependency disabled]" if not deps_ok else "")
            attr = curses.A_REVERSE if i == pos else 0
            if not deps_ok: attr |= curses.A_DIM
            put(row, text, attr); row += 1
        stdscr.refresh(); ch = stdscr.getch()
        if ch in (ord('q'), 27): return False
        if ch == ord('s'): save(v); return True
        if ch in (curses.KEY_UP, ord('k')): pos = (pos - 1) % len(OPTIONS)
        elif ch in (curses.KEY_DOWN, ord('j')): pos = (pos + 1) % len(OPTIONS)
        elif ch in (ord(' '), 10, 13):
            key = OPTIONS[pos][1]
            if key in ("ARCH_ARM", "ARCH_ARM64"):
                v["ARCH_ARM"] = key == "ARCH_ARM"; v["ARCH_ARM64"] = key == "ARCH_ARM64"
            elif all(v.get(d) for d in DEPS.get(key, ())): v[key] = not v.get(key)
            normalize(v)

def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--defconfig":
        v = load(ROOT / sys.argv[2]); save(v); return
    v = load()
    saved = curses.wrapper(run, v)
    print("Configuration saved to .config" if saved else "Configuration not saved")

if __name__ == "__main__": main()
